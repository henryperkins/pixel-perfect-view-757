async page => {
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  const check=(condition,message)=>{if(!condition)throw Error(message);};
  const calls=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('mock-calls')||'[]'));
  await page.goto('http://127.0.0.1:5212');
  await page.evaluate(()=>localStorage.clear());
  await page.reload();
  const open=()=>page.getByRole('button',{name:'Evaluate this draft',exact:true}).click();
  await open();
  await page.getByRole('button',{name:'Prepare eight-call pilot',exact:true}).click();
  await page.getByRole('button',{name:'Start baseline · $5 cap',exact:true}).waitFor();
  check((await calls()).filter(x=>x.kind==='start').length===0,'Preparation started generation');
  check((await calls()).filter(x=>x.kind==='preview').at(-1).data.caseSetId==='draft-pilot-2','Wrong preview manifest');
  await page.getByRole('button',{name:'Close draft evaluation',exact:true}).click();
  await page.getByRole('button',{name:'Evaluate this draft',exact:true}).press('Enter');
  await page.getByRole('button',{name:'Start baseline · $5 cap',exact:true}).waitFor();
  await page.getByLabel('Draft source').selectOption('other-draft');
  await open();
  check(await page.getByRole('button',{name:'Start baseline · $5 cap',exact:true}).count()===0,'Source switch retained preparation');
  await page.getByLabel('Draft source').selectOption('draft-fixture');
  await open();
  await page.getByRole('button',{name:'Prepare eight-call pilot',exact:true}).click();
  await page.getByRole('button',{name:'Start baseline · $5 cap',exact:true}).waitFor();
  const pairDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download frozen pair',exact:true}).click();
  await (await pairDownload).saveAs('output/playwright/content-repair-pilot/mock-frozen-pair.json');
  await page.screenshot({path:'output/playwright/content-repair-pilot/desktop-prepared.png',fullPage:true});
  await page.getByRole('button',{name:'Start baseline · $5 cap',exact:true}).click();
  await page.getByRole('button',{name:'Prepare candidate from frozen campaign',exact:true}).waitFor();
  await page.reload(); await open();
  await page.getByRole('button',{name:'Prepare candidate from frozen campaign',exact:true}).waitFor();
  await page.getByRole('button',{name:'Prepare candidate from frozen campaign',exact:true}).click();
  await page.getByRole('button',{name:'Start candidate · remaining campaign budget',exact:true}).click();
  await page.getByText('Candidate: complete · 4/4 cases captured.',{exact:true}).waitFor();
  const starts=(await calls()).filter(x=>x.kind==='start');
  check(starts.length===2&&starts.every(x=>x.data.caseSetId==='draft-pilot-2'),'Wrong starts or manifest');
  check(starts[0].data.budget.dollarCeilingCents===500&&starts[0].data.budget.reviewReserveCents===0,'Wrong baseline cap');
  check(!('budget' in starts[1].data)&&starts[1].data.campaignId==='11111111-1111-4111-8111-111111111111','Candidate replaced campaign budget');
  check(await page.evaluate(()=>localStorage.getItem('pattern-content-repair-pilot:admin-fixture:draft:draft-fixture'))==='22222222-2222-4222-8222-222222222222','Wrong repair recovery identity');
  await page.setViewportSize({width:390,height:844});
  check(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Mobile overflow');
  await page.screenshot({path:'output/playwright/content-repair-pilot/mobile-completed.png',fullPage:true});
  await page.evaluate(()=>{
    const state=JSON.parse(localStorage.getItem('mock-server'));
    const old=state.runs[state.latest];
    old.run.contentComparison.arm='baseline';
    old.run.contentComparison.caseSetId='draft-pilot-1';
    old.ledger.sourcePlan.contentComparison.pair.version='content-comparison-1';
    old.ledger.sourcePlan.contentComparison.pair.caseSetId='draft-pilot-1';
    localStorage.removeItem('pattern-content-repair-pilot:admin-fixture:draft:draft-fixture');
    localStorage.setItem('mock-server',JSON.stringify(state));
  });
  await page.reload(); await open();
  await page.getByRole('button',{name:'Prepare eight-call pilot',exact:true}).waitFor();
  check(await page.getByRole('button',{name:'Prepare candidate from frozen campaign',exact:true}).count()===0,'Recovered an original campaign as a repair');
  check(errors.length===0,JSON.stringify(errors));
  return {transport:'mocked',modelCalls:0,viewports:[1440,390],checks:['explicit v2 preview/start','zero automatic generation','source switch clears preparation','keyboard and retained panel','frozen pair download','baseline $5 cap','candidate uses frozen campaign and budget','repair recovery survives reload','original campaign excluded','no overflow','no page or console errors'],errors};
}
